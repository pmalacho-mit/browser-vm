// The web gate's part of an app build (see tools/lib/app.mjs):
//
//   src/relay.ts  → site/host/gate-relay.js     on every page that hosts a VM (a no-op when the app has no gate)
//   app/gate.ts   → gate/gate.js (+ chunks/)    the gate's own origin; ES module, since its CSP is script-src 'self'
//   app/index.html, gate.css → gate/            (tools/ writes gate/site.js)
//   bridge-extension/ → bridge-extension/       optional Chrome extension, set up for this app's gate origin
import fs from "node:fs";
import path from "node:path";

const here = import.meta.dirname;

/** @returns {import("@browser-vm/tools/app").Part} */
export default function gateWebPart() {
  return {
    name: "gate",
    bundles: (ctx) => /** @type {{ name: string, options: import("esbuild").BuildOptions }[]} */ ([
      {
        name: "gate relay",
        options: { ...ctx.common, entryPoints: { "gate-relay": path.join(here, "src/relay.ts") }, outdir: path.join(ctx.out.site, "host"), format: "iife" },
      },
      ...(ctx.app.gate === "web" ? [{
        name: "gate",
        options: {
          ...ctx.common,
          entryPoints: [path.join(here, "app/gate.ts")],
          outdir: ctx.out.gate,
          format: "esm",
          // The settings popup (manage.ts) is loaded on demand, as its own file.
          splitting: true,
          chunkNames: "chunks/[name]-[hash]",
        },
      }] : []),
    ]),
    assemble(ctx) {
      if (ctx.app.gate !== "web") return;
      fs.mkdirSync(ctx.out.gate, { recursive: true });
      for (const f of ["index.html", "gate.css"]) fs.copyFileSync(path.join(here, "app", f), path.join(ctx.out.gate, f));

      // The bridge extension, with this app's gate origin filled in: Chrome loads it unpacked.
      const gateOrigin = ctx.origins.gate ? new URL(ctx.origins.gate).origin : "http://gate.localhost:8080";
      const out = path.join(ctx.out.extras, "bridge-extension");
      fs.rmSync(out, { recursive: true, force: true });
      fs.cpSync(path.join(here, "bridge-extension"), out, { recursive: true, filter: (f) => !f.endsWith("README.md") });
      const policy = path.join(out, "policy.js");
      const src = fs.readFileSync(policy, "utf8");
      if (!/^export const APP_ORIGINS = \[.*\];$/m.test(src)) throw new Error("gates/web/bridge-extension/policy.js: APP_ORIGINS line not found");
      fs.writeFileSync(policy, src.replace(/^export const APP_ORIGINS = \[.*\];$/m, `export const APP_ORIGINS = ${JSON.stringify([gateOrigin])}; // generated by gates/web/build.mjs`));
      const manifest = JSON.parse(fs.readFileSync(path.join(out, "manifest.json"), "utf8"));
      // Match patterns have no port: "http://gate.localhost/*" matches any.
      manifest.content_scripts[0].matches = [`${new URL(gateOrigin).protocol}//${new URL(gateOrigin).hostname}/*`];
      fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
    },
    watch: [path.join(here, "app"), path.join(here, "bridge-extension")],
  };
}
