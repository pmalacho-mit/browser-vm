// Assembles the static site in dist/. Upload dist/ to any static host.
//
//   npm run build                    32-bit VM (upstream v86), the default
//   npm run build:x86_64             64-bit VM (v86_64 fork, experimental); or VM_ARCH=x86_64
//   (scripts/targets.mjs says which emulator, kernel and guest image each uses)
//
//   dist/
//     index.html                      host page (web/index.html)
//     gate-relay.js, boot.js, amd-config.js   its scripts (web/*.ts)
//     gate/                           the network gate (web/gate/), served on its own origin
//     vscode/                         Code-OSS web workbench (npm: vscode-web)
//     extensions/linux-vm/
//       package.json, dist/extension.js   the bridge (extension/src, bundled with esbuild)
//       vm/                           everything the VM needs:
//         v86.wasm                    x86 → WASM JIT emulator
//         seabios.bin, vgabios.bin    PC firmware
//         bzImage                     Linux kernel (guest/build-kernel.sh)
//         fs.json, rootfs/            root filesystem from guest/Dockerfile
//         tls.wasm                    in-browser TLS terminator for guest HTTPS (tls/)
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { copyStatic, esbuildTargets } from "./esbuild.config.mjs";
import { target } from "./targets.mjs";
import { createHash } from "node:crypto";

const root = path.resolve(import.meta.dirname, "..");
const fromRoot = (...p) => path.join(root, ...p);
const dist = fromRoot("dist");
const ext = path.join(dist, "extensions/linux-vm");
const vmDir = path.join(ext, "vm");
const vm = target(root); // --arch= or $VM_ARCH: i686 (default) or x86_64

const pick = (/** @type {string[]} */ ...candidates) => {
  const found = candidates.find((c) => fs.existsSync(fromRoot(c)));
  if (!found) throw new Error(`none of these exist: ${candidates.join(", ")}`);
  return found;
};

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(vmDir, { recursive: true });

// 1. host page + workbench. The page's scripts, the gate and the extension are
// compiled in step 2; this copies their HTML/CSS and the extension manifest.
copyStatic(dist);
fs.cpSync(fromRoot("node_modules/vscode-web/dist"), path.join(dist, "vscode"), { recursive: true });
fs.writeFileSync(path.join(dist, ".nojekyll"), ""); // GitHub Pages: serve node_modules/ too

// Deployment origins: IDE_URL and GATE_URL, both or neither. index.html reads
// where the gate is; the gate reads which IDE may embed it. Both origins serve
// this same dist/. Production: IDE_URL=https://ide.example.com/
// GATE_URL=https://gate.example.com/. Also for port forwarders that route one
// exact hostname per port (see the build:desolate script). Neither set: the
// local default, IDE on http://localhost:<port> and gate on gate.localhost.
// Only these two variables count, so where the build runs never changes the output.
{
  const { IDE_URL: ideUrl, GATE_URL: gateUrl, PREVIEW_URL: previewUrl } = process.env;
  if (!ideUrl !== !gateUrl) throw new Error("set both IDE_URL and GATE_URL, or neither");
  const site = ideUrl && gateUrl ? { ideUrl: new URL(ideUrl).href, gateUrl: new URL(gateUrl).href } : {};
  if (ideUrl && gateUrl && new URL(ideUrl).origin === new URL(gateUrl).origin) throw new Error("IDE_URL and GATE_URL must be different origins");
  // Previews of servers in the VM: one origin per port, e.g. https://{id}.preview.example.com/
  // (wildcard DNS and certificate, serving dist/ at the root). Locally: *.preview.localhost.
  if (previewUrl) {
    if (!/^https?:\/\/\{id\}\.[^/]+\/?$/.test(previewUrl)) throw new Error("PREVIEW_URL must look like https://{id}.preview.example.com/");
    Object.assign(site, { previewUrl });
  }
  fs.writeFileSync(path.join(dist, "site.js"),
    `// Generated by scripts/build-site.mjs.\nself.SITE_CONFIG = ${JSON.stringify(site)};\n` +
    `if (self.SITE_CONFIG.gateUrl && !self.GATE_URL) self.GATE_URL = self.SITE_CONFIG.gateUrl;\n`);
  if (site.gateUrl) console.log(`gate:   ${site.gateUrl} (embedded by ${site.ideUrl})`);
  if (previewUrl) console.log(`preview: ${previewUrl}`);

  // The optional bridge extension (bridge-extension/), with this site's gate
  // origin filled in: Chrome loads it unpacked from build/bridge-extension/.
  const gateOrigin = site.gateUrl ? new URL(site.gateUrl).origin : "http://gate.localhost:8080";
  const bridge = fromRoot("build/bridge-extension");
  fs.rmSync(bridge, { recursive: true, force: true });
  fs.cpSync(fromRoot("bridge-extension"), bridge, { recursive: true, filter: (f) => !f.endsWith("README.md") });
  const policy = path.join(bridge, "policy.js");
  const policySrc = fs.readFileSync(policy, "utf8");
  if (!/^export const APP_ORIGINS = \[.*\];$/m.test(policySrc)) throw new Error("bridge-extension/policy.js: APP_ORIGINS line not found");
  fs.writeFileSync(policy, policySrc.replace(/^export const APP_ORIGINS = \[.*\];$/m, `export const APP_ORIGINS = ${JSON.stringify([gateOrigin])}; // generated by scripts/build-site.mjs`));
  const manifest = JSON.parse(fs.readFileSync(path.join(bridge, "manifest.json"), "utf8"));
  // Match patterns have no port: "http://gate.localhost/*" matches any.
  manifest.content_scripts[0].matches = [`${new URL(gateOrigin).protocol}//${new URL(gateOrigin).hostname}/*`];
  fs.writeFileSync(path.join(bridge, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  console.log(`bridge: build/bridge-extension/ (optional Chrome extension, for the gate at ${gateOrigin})`);
}

// Lock down the extension host. Every web extension (ours, and any installed
// from Open VSX) runs in a worker created by this iframe and inherits its CSP.
// Upstream allows connect-src/script-src to ANY https: origin, so any extension
// could send data anywhere and skip the network gate. Here they get their own
// origin (plus Open VSX, where gallery extensions' code lives) and nothing else;
// the VM's traffic goes through the gate over a BroadcastChannel instead.
{
  const f = path.join(dist, "vscode/out/vs/workbench/services/extensions/worker/webWorkerExtensionHostIframe.html");
  const html = fs.readFileSync(f, "utf8");
  // A worker started from a URL takes its CSP from HTTP headers (static hosts
  // often can't set any), not from this page. A worker started from a blob:
  // URL inherits this page's CSP, and so does every blob worker IT starts. So
  // start the extension host through a one-line blob that loads the real script.
  const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
  if (!script) throw new Error("extension host iframe: no inline script found (vscode-web changed?)");
  const wrapped = script.replace("const worker = new Worker(workerUrl, { name });",
    "const workerAbs = new URL(workerUrl, location.href); " +
    // workerMain.js resolves modules against its own URL unless told otherwise; a blob has none.
    "const worker = new Worker(URL.createObjectURL(new Blob([`globalThis.MonacoEnvironment = { baseUrl: ${JSON.stringify(new URL('../../../', workerAbs).href)} }; importScripts(${JSON.stringify(workerAbs.href)});`], { type: 'text/javascript' })), { name }); // CSP-inheriting (build-site.mjs)");
  if (wrapped === script) throw new Error("could not wrap the extension host worker (vscode-web changed?)");
  const hash = (t) => `'sha256-${createHash("sha256").update(t).digest("base64")}'`;
  if (!html.includes(hash(script))) throw new Error("extension host iframe: inline script hash mismatch (vscode-web changed?)");
  const locked = html
    .replace(script, wrapped)
    .replace(hash(script), hash(wrapped))
    .replace(/connect-src [^;]*;/, "connect-src 'self' https://open-vsx.org;")
    // blob: lets v86 start its scheduler worker; it adds no network reach (connect-src decides that).
    .replace(/(script-src [^;]*?) https:;/, "$1 blob: https://open-vsx.org;");
  if (/connect-src[^;]*https:;/.test(locked)) throw new Error("could not patch the extension host CSP (vscode-web changed?)");
  fs.writeFileSync(f, locked);
}

// 2. TypeScript: the bridge extension, the host page's scripts and the gate (scripts/esbuild.config.mjs)
await Promise.all(esbuildTargets(dist, vm).map(({ options }) => build(options)));

// 3. VM assets for the selected architecture (locally built kernel/guest win over guest/prebuilt)
fs.copyFileSync(vm.wasm, path.join(vmDir, "v86.wasm"));
fs.copyFileSync(vm.wasmFallback, path.join(vmDir, "v86-fallback.wasm"));
for (const f of ["seabios.bin", "vgabios.bin"]) fs.copyFileSync(fromRoot("vendor", f), path.join(vmDir, f));
const kernel = path.relative(root, vm.kernel);
fs.copyFileSync(vm.kernel, path.join(vmDir, "bzImage"));
const tlsWasm = pick("build/tls/tls.wasm", "tls/prebuilt/tls.wasm");
fs.copyFileSync(fromRoot(tlsWasm), path.join(vmDir, "tls.wasm"));
const guest = path.relative(root, vm.guest);
fs.copyFileSync(fromRoot(guest, "fs.json"), path.join(vmDir, "fs.json"));
fs.cpSync(fromRoot(guest, "rootfs"), path.join(vmDir, "rootfs"), { recursive: true });
// guest/agent, written into the guest before boot (without it, the image's shell agent runs)
if (vm.agent) fs.copyFileSync(vm.agent, path.join(vmDir, "vm-agent"));

// 4. Playgrounds (npm run playgrounds → build/playgrounds): snapshots restore
// only on the emulator and kernel they were built with, so ship the ones that
// match this build, with the blobs their file index references.
const playgrounds = [];
{
  const src = fromRoot("build/playgrounds");
  const id16 = (/** @type {string} */ f) => createHash("sha256").update(fs.readFileSync(f)).digest("hex").slice(0, 16);
  const emulator = id16(vm.wasm), kernelId = id16(vm.kernel);
  const dirs = fs.existsSync(src) ? fs.readdirSync(src).filter((d) => fs.existsSync(path.join(src, d, "manifest.json"))) : [];
  for (const id of dirs) {
    const m = JSON.parse(fs.readFileSync(path.join(src, id, "manifest.json"), "utf8"));
    const why = m.arch !== vm.arch ? `built for ${m.arch}` : m.emulator !== emulator ? "built with another emulator" : m.kernel !== kernelId ? "built with another kernel" : null;
    if (why) { console.warn(`playground ${id}: skipped (${why}; rebuild with npm run playgrounds)`); continue; }
    const out = path.join(vmDir, "playgrounds", id);
    fs.mkdirSync(out, { recursive: true });
    for (const f of ["manifest.json", m.state]) fs.copyFileSync(path.join(src, id, f), path.join(out, f));
    // Every file in the playground's index (fs.json) is a blob in the shared pool.
    /** @type {(entries: any[]) => void} */
    const walk = (entries) => {
      for (const e of entries) {
        const [, , , mode, , , target] = e;
        if ((mode & 0xf000) === 0x4000) walk(target);
        else if ((mode & 0xf000) === 0x8000 && typeof target === "string") {
          const to = path.join(vmDir, "rootfs", target);
          if (!fs.existsSync(to)) fs.copyFileSync(path.join(src, "rootfs", target), to);
        }
      }
    };
    walk(JSON.parse(fs.readFileSync(path.join(src, id, "fs.json"), "utf8")).fsroot);
    playgrounds.push({ id, title: m.title, description: m.description, memoryMB: m.memoryMB, packages: m.packages });
  }
  fs.mkdirSync(path.join(vmDir, "playgrounds"), { recursive: true });
  fs.writeFileSync(path.join(vmDir, "playgrounds", "index.json"), JSON.stringify(playgrounds, null, 2) + "\n");
}

const size = (/** @type {string} */ dir) => fs.readdirSync(dir, { recursive: true, encoding: "utf8" }).reduce((n, f) => {
  const s = fs.statSync(path.join(dir, f)); return n + (s.isFile() ? s.size : 0);
}, 0);
console.log(`VM:     ${vm.arch}, ${vm.description}\nemu:   ${path.relative(root, path.dirname(vm.wasm))}\nkernel: ${kernel}\nguest:  ${guest}\nagent:  ${vm.agent ? path.relative(root, vm.agent) : "(the image's shell agent)"}\ntls:    ${tlsWasm}`);
console.log(`playgrounds: ${playgrounds.map((p) => p.id).join(", ") || "none (npm run playgrounds)"}`);
console.log(`dist/ built: ${(size(dist) / 1e6).toFixed(1)} MB  (VM assets ${(size(vmDir) / 1e6).toFixed(1)} MB)`);
console.log(`serve it with:  npm start   (or any static file server)`);
