// Assembles the static site in dist/. Upload dist/ to any static host.
//
//   dist/
//     index.html                      host page (web/index.html)
//     vscode/                         Code-OSS web workbench (npm: vscode-web)
//     extensions/linux-vm/
//       package.json, dist/extension.js   the bridge (bundled with esbuild)
//       vm/                           everything the VM needs:
//         v86.wasm                    x86 → WASM JIT emulator
//         seabios.bin, vgabios.bin    PC firmware
//         bzImage                     Linux kernel (guest/build-kernel.sh)
//         fs.json, rootfs/            root filesystem from guest/Dockerfile
//         tls.wasm                    in-browser TLS terminator for guest HTTPS (tls/)
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const r = (...p) => path.join(root, ...p);
const dist = r("dist");
const ext = path.join(dist, "extensions/linux-vm");
const vmDir = path.join(ext, "vm");

const pick = (...candidates) => {
  const found = candidates.find((c) => fs.existsSync(r(c)));
  if (!found) throw new Error(`none of these exist: ${candidates.join(", ")}`);
  return found;
};

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(vmDir, { recursive: true });

// 1. host page + workbench
fs.copyFileSync(r("web/index.html"), path.join(dist, "index.html"));
fs.copyFileSync(r("web/gate-relay.js"), path.join(dist, "gate-relay.js"));
// the network gate (served on its own origin, e.g. gate.localhost / gate.example.com)
fs.cpSync(r("web/gate"), path.join(dist, "gate"), { recursive: true, filter: (f) => !f.endsWith("package.json") });
fs.cpSync(r("node_modules/vscode-web/dist"), path.join(dist, "vscode"), { recursive: true });
fs.writeFileSync(path.join(dist, ".nojekyll"), ""); // GitHub Pages: serve node_modules/ too

// Deployment origins: IDE_URL and GATE_URL, both or neither. index.html reads
// where the gate is; the gate reads which IDE may embed it. Both origins serve
// this same dist/. Production: IDE_URL=https://ide.example.com/
// GATE_URL=https://gate.example.com/. Also for port forwarders that route one
// exact hostname per port (see the build:desolate script). Neither set: the
// local default, IDE on http://localhost:<port> and gate on gate.localhost.
// Only these two variables count, so where the build runs never changes the output.
{
  const { IDE_URL: ideUrl, GATE_URL: gateUrl } = process.env;
  if (!ideUrl !== !gateUrl) throw new Error("set both IDE_URL and GATE_URL, or neither");
  const site = ideUrl ? { ideUrl: new URL(ideUrl).href, gateUrl: new URL(gateUrl).href } : {};
  if (ideUrl && new URL(ideUrl).origin === new URL(gateUrl).origin) throw new Error("IDE_URL and GATE_URL must be different origins");
  fs.writeFileSync(path.join(dist, "site.js"),
    `// Generated by scripts/build-site.mjs.\nself.SITE_CONFIG = ${JSON.stringify(site)};\n` +
    `if (self.SITE_CONFIG.gateUrl && !self.GATE_URL) self.GATE_URL = self.SITE_CONFIG.gateUrl;\n`);
  if (site.gateUrl) console.log(`gate:   ${site.gateUrl} (embedded by ${site.ideUrl})`);
}

// Lock down the extension host. Every web extension (ours, and any installed
// from Open VSX) runs in a worker created by this iframe and inherits its CSP.
// Upstream allows connect-src/script-src to ANY https: origin, so any extension
// could send data anywhere and skip the network gate. Here they get their own
// origin (plus Open VSX, where gallery extensions' code lives) and nothing else;
// the VM's traffic goes through the gate over a BroadcastChannel instead.
{
  const f = path.join(dist, "vscode/out/vs/workbench/services/extensions/worker/webWorkerExtensionHostIframe.html");
  const html = fs.readFileSync(f, "utf8");
  // A worker started from a URL takes its CSP from HTTP headers (static hosts
  // often can't set any), not from this page. A worker started from a blob:
  // URL inherits this page's CSP, and so does every blob worker IT starts. So
  // start the extension host through a one-line blob that loads the real script.
  const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
  const wrapped = script.replace("const worker = new Worker(workerUrl, { name });",
    "const workerAbs = new URL(workerUrl, location.href); " +
    // workerMain.js resolves modules against its own URL unless told otherwise; a blob has none.
    "const worker = new Worker(URL.createObjectURL(new Blob([`globalThis.MonacoEnvironment = { baseUrl: ${JSON.stringify(new URL('../../../', workerAbs).href)} }; importScripts(${JSON.stringify(workerAbs.href)});`], { type: 'text/javascript' })), { name }); // CSP-inheriting (build-site.mjs)");
  if (wrapped === script) throw new Error("could not wrap the extension host worker (vscode-web changed?)");
  const { createHash } = await import("node:crypto");
  const hash = (t) => `'sha256-${createHash("sha256").update(t).digest("base64")}'`;
  if (!html.includes(hash(script))) throw new Error("extension host iframe: inline script hash mismatch (vscode-web changed?)");
  const locked = html
    .replace(script, wrapped)
    .replace(hash(script), hash(wrapped))
    .replace(/connect-src [^;]*;/, "connect-src 'self' https://open-vsx.org;")
    // blob: lets v86 start its scheduler worker; it adds no network reach (connect-src decides that).
    .replace(/(script-src [^;]*?) https:;/, "$1 blob: https://open-vsx.org;");
  if (/connect-src[^;]*https:;/.test(locked)) throw new Error("could not patch the extension host CSP (vscode-web changed?)");
  fs.writeFileSync(f, locked);
}

// 2. bridge extension
await build({
  entryPoints: [r("extension/src/extension.js")],
  outfile: path.join(ext, "dist/extension.js"),
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2022",
  // v86 also has Node code paths (guarded at runtime); leave those imports alone.
  external: ["vscode", "node:*", ...(await import("node:module")).builtinModules],
  minify: false,
  sourcemap: true,
  logLevel: "warning",
});
for (const f of ["package.json", "package.nls.json"]) fs.copyFileSync(r("extension", f), path.join(ext, f));

// 3. VM assets (locally built ones win over the prebuilt ones shipped in guest/prebuilt)
for (const f of ["v86.wasm", "v86-fallback.wasm"]) fs.copyFileSync(r("node_modules/v86/build", f), path.join(vmDir, f));
for (const f of ["seabios.bin", "vgabios.bin"]) fs.copyFileSync(r("vendor", f), path.join(vmDir, f));
const kernel = pick("build/kernel/bzImage", "guest/prebuilt/bzImage");
fs.copyFileSync(r(kernel), path.join(vmDir, "bzImage"));
const tlsWasm = pick("build/tls/tls.wasm", "tls/prebuilt/tls.wasm");
fs.copyFileSync(r(tlsWasm), path.join(vmDir, "tls.wasm"));
const guest = pick("build/guest", "guest/prebuilt/guest");
fs.copyFileSync(r(guest, "fs.json"), path.join(vmDir, "fs.json"));
fs.cpSync(r(guest, "rootfs"), path.join(vmDir, "rootfs"), { recursive: true });

const size = (dir) => fs.readdirSync(dir, { recursive: true }).reduce((n, f) => {
  const s = fs.statSync(path.join(dir, f)); return n + (s.isFile() ? s.size : 0);
}, 0);
console.log(`kernel: ${kernel}\nguest:  ${guest}\ntls:    ${tlsWasm}`);
console.log(`dist/ built: ${(size(dist) / 1e6).toFixed(1)} MB  (VM assets ${(size(vmDir) / 1e6).toFixed(1)} MB)`);
console.log(`serve it with:  npm start   (or any static file server)`);
